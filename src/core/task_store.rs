pub fn record_session(
    ws_root: &Path,
    task_id: Option<&str>,
    session_id: &str,
    host: &str,
    title: &str,
    category: Option<&str>,
    role: &str,
) -> Result<Value, WbError> {
    let s_id = session_id.trim();
    if s_id.is_empty() {
        return Err(WbError::validation("session_id 不能为空"));
    }
    let s_host = if host.trim().is_empty() {
        "localhost"
    } else {
        host.trim()
    };
    let (norm_title, prefix, inferred_cat) = parse_and_validate_session_title(title)?;
    let s_cat = match category {
        Some(c) if !c.is_empty() => validate_category(c)?,
        _ => inferred_cat.unwrap_or_else(|| "unclassified".to_string()),
    };
    if role != "origin" && role != "associated" {
        return Err(WbError::validation(format!(
            "会话角色必须为 origin 或 associated，收到: {role:?}"
        )));
    }
    let ts = now_iso();

    if let Some(tid) = task_id {
        let tdir = require_task_dir(ws_root, tid)?;
        with_task_lock(&tdir, |_| {
            let mut data = validate_task_dict(&read_yaml_file(&tdir.join("task.yaml"))?)?;
            let obj = data.as_object_mut().unwrap();
            let mut sessions_obj = obj
                .get("sessions")
                .and_then(|v| v.as_object())
                .cloned()
                .unwrap_or_default();

            let origin = sessions_obj.get("origin").and_then(|v| v.as_object()).cloned();
            let mut associated: Vec<Map<String, Value>> = sessions_obj
                .get("associated")
                .and_then(|v| v.as_array())
                .map(|arr| {
                    arr.iter()
                        .filter_map(|x| x.as_object().cloned())
                        .collect()
                })
                .unwrap_or_default();

            let mut entry = Map::new();
            entry.insert("session_id".into(), Value::String(s_id.to_string()));
            entry.insert("host".into(), Value::String(s_host.to_string()));
            entry.insert("title".into(), Value::String(norm_title.clone()));
            entry.insert(
                "prefix".into(),
                prefix.clone().map(Value::String).unwrap_or(Value::Null),
            );
            entry.insert("category".into(), Value::String(s_cat.clone()));
            entry.insert("recorded_at".into(), Value::String(ts.clone()));

            let same_key = |m: &Map<String, Value>| {
                m.get("session_id").and_then(|v| v.as_str()) == Some(s_id)
                    && m.get("host").and_then(|v| v.as_str()) == Some(s_host)
            };

            if role == "origin" {
                if let Some(prev_origin) = origin {
                    let prev_sid = prev_origin.get("session_id").and_then(|v| v.as_str()).unwrap_or("");
                    let prev_host = prev_origin.get("host").and_then(|v| v.as_str()).unwrap_or("");
                    if !(prev_sid == s_id && prev_host == s_host)
                        && !associated.iter().any(|a| {
                            a.get("session_id").and_then(|v| v.as_str()) == Some(prev_sid)
                                && a.get("host").and_then(|v| v.as_str()) == Some(prev_host)
                        })
                    {
                        associated.push(prev_origin);
                    }
                }
                associated.retain(|a| !same_key(a));
                sessions_obj.insert("origin".into(), Value::Object(entry));
            } else if origin.as_ref().map(same_key).unwrap_or(false) {
                sessions_obj.insert("origin".into(), Value::Object(entry));
            } else if let Some(pos) = associated.iter().position(same_key) {
                associated[pos] = entry;
            } else {
                associated.push(entry);
            }

            sessions_obj.insert(
                "associated".into(),
                Value::Array(associated.into_iter().map(Value::Object).collect()),
            );
            obj.insert("sessions".into(), Value::Object(sessions_obj));
            obj.insert("updated_at".into(), Value::String(ts.clone()));
            atomic_write_yaml(&tdir.join("task.yaml"), &data)?;
            Ok(())
        })?;
    }

    with_workspace_lock(ws_root, |_| {
        let entry = upsert_session_ledger_locked(
            ws_root,
            s_id,
            s_host,
            &norm_title,
            prefix.as_deref(),
            &s_cat,
            task_id,
            &ts,
        )?;
        if task_id.is_some() {
            rebuild_index(ws_root)?;
        }
        Ok(entry)
    })
}

pub fn list_tasks(
    ws_root: &Path,
    status: Option<&str>,
    category: Option<&str>,
    priority: Option<&str>,
    owner: Option<&str>,
) -> Result<Vec<Value>, WbError> {
    let t_root = tasks_root(ws_root);
    if !t_root.is_dir() {
        return Ok(Vec::new());
    }
    let mut dirs: Vec<PathBuf> = fs::read_dir(&t_root)
        .map_err(|e| WbError::io(format!("读取 tasks 目录失败: {e}")))?
        .filter_map(|e| e.ok().map(|x| x.path()))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();

    let mut out = Vec::new();
    for child in dirs {
        let tfile = child.join("task.yaml");
        if !tfile.is_file() {
            continue;
        }
        let data = validate_task_dict(&read_yaml_file(&tfile)?)?;
        if let Some(st) = status {
            if data.get("status").and_then(|v| v.as_str()) != Some(st) {
                continue;
            }
        }
        if let Some(cat) = category {
            if data.get("category").and_then(|v| v.as_str()) != Some(cat) {
                continue;
            }
        }
        if let Some(prio) = priority {
            if data.get("priority").and_then(|v| v.as_str()) != Some(prio) {
                continue;
            }
        }
        if let Some(own) = owner {
            if data.get("owner").and_then(|v| v.as_str()) != Some(own) {
                continue;
            }
        }
        out.push(data);
    }
    Ok(out)
}

pub fn compute_task_stats(ws_root: &Path) -> Result<Value, WbError> {
    let tasks = list_tasks(ws_root, None, None, None, None)?;
    let mut by_status: BTreeMap<String, i64> = VALID_STATUSES
        .iter()
        .map(|s| ((*s).to_string(), 0))
        .collect();
    let mut by_category: BTreeMap<String, i64> = VALID_CATEGORIES
        .iter()
        .map(|c| ((*c).to_string(), 0))
        .collect();
    let mut by_priority: BTreeMap<String, i64> = VALID_PRIORITIES
        .iter()
        .map(|p| ((*p).to_string(), 0))
        .collect();

    for t in &tasks {
        let st = t.get("status").and_then(|v| v.as_str()).unwrap_or("planning");
        let cat = t.get("category").and_then(|v| v.as_str()).unwrap_or("unclassified");
        let prio = t.get("priority").and_then(|v| v.as_str()).unwrap_or("P2");
        *by_status.entry(st.to_string()).or_insert(0) += 1;
        *by_category.entry(cat.to_string()).or_insert(0) += 1;
        *by_priority.entry(prio.to_string()).or_insert(0) += 1;
    }

    let ledger = load_session_ledger(ws_root)?;
    let sess_count = ledger
        .get("sessions")
        .and_then(|v| v.as_array())
        .map(|a| a.len())
        .unwrap_or(0);

    let mut m = Map::new();
    m.insert("total_tasks".into(), Value::from(tasks.len() as i64));
    m.insert(
        "by_status".into(),
        Value::Object(by_status.into_iter().map(|(k, v)| (k, Value::from(v))).collect()),
    );
    m.insert(
        "by_category".into(),
        Value::Object(by_category.into_iter().map(|(k, v)| (k, Value::from(v))).collect()),
    );
    m.insert(
        "by_priority".into(),
        Value::Object(by_priority.into_iter().map(|(k, v)| (k, Value::from(v))).collect()),
    );
    m.insert("total_sessions".into(), Value::from(sess_count as i64));
    Ok(Value::Object(m))
}
