pub fn manage_milestones(
    ws_root: &Path,
    task_id: &str,
    action: &str,
    title: &str,
    done: bool,
) -> Result<Value, WbError> {
    let tdir = require_task_dir(ws_root, task_id)?;
    let ts = now_iso();
    let clean_title = title.trim();

    let updated = with_task_lock(&tdir, |_| {
        let mut data = validate_task_dict(&read_yaml_file(&tdir.join("task.yaml"))?)?;
        let obj = data.as_object_mut().unwrap();
        let mut milestones: Vec<Map<String, Value>> = obj
            .get("milestones")
            .and_then(|v| v.as_array())
            .map(|arr| {
                arr.iter()
                    .map(|item| match item.as_object() {
                        Some(m) => m.clone(),
                        None => {
                            let mut m = Map::new();
                            m.insert("title".into(), Value::String(item.as_str().unwrap_or("").to_string()));
                            m.insert("done".into(), Value::Bool(false));
                            m.insert("updated_at".into(), Value::String(ts.clone()));
                            m
                        }
                    })
                    .collect()
            })
            .unwrap_or_default();

        match action {
            "add" => {
                if clean_title.is_empty() {
                    return Err(WbError::validation("里程碑标题不能为空"));
                }
                if !milestones
                    .iter()
                    .any(|m| m.get("title").and_then(|v| v.as_str()) == Some(clean_title))
                {
                    let mut m = Map::new();
                    m.insert("title".into(), Value::String(clean_title.to_string()));
                    m.insert("done".into(), Value::Bool(done));
                    m.insert("updated_at".into(), Value::String(ts.clone()));
                    milestones.push(m);
                }
            }
            "complete" | "reopen" => {
                let mut found = false;
                for m in &mut milestones {
                    if m.get("title").and_then(|v| v.as_str()) == Some(clean_title) {
                        m.insert("done".into(), Value::Bool(action == "complete"));
                        m.insert("updated_at".into(), Value::String(ts.clone()));
                        found = true;
                        break;
                    }
                }
                if !found {
                    return Err(WbError::not_found(format!("未找到里程碑: {clean_title}")));
                }
            }
            "remove" => {
                let before = milestones.len();
                milestones.retain(|m| m.get("title").and_then(|v| v.as_str()) != Some(clean_title));
                if milestones.len() == before {
                    return Err(WbError::not_found(format!("未找到里程碑: {clean_title}")));
                }
            }
            _ => return Err(WbError::validation(format!("不支持的里程碑操作: {action}"))),
        }

        obj.insert(
            "milestones".into(),
            Value::Array(milestones.into_iter().map(Value::Object).collect()),
        );
        obj.insert("updated_at".into(), Value::String(ts.clone()));
        atomic_write_yaml(&tdir.join("task.yaml"), &data)?;
        Ok(data)
    })?;

    with_workspace_lock(ws_root, |_| {
        rebuild_index(ws_root)?;
        Ok(())
    })?;
    Ok(updated)
}

