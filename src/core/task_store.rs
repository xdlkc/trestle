pub const INDEX_HEADER: &str = "<!-- AUTO-GENERATED BY wb - DO NOT EDIT MANUALLY -->";

pub fn tasks_root(ws_root: &Path) -> PathBuf {
    ws_root.join("tasks")
}

pub fn task_dir_for(ws_root: &Path, task_id: &str) -> Result<PathBuf, WbError> {
    let safe_id = validate_task_id(task_id)?;
    Ok(tasks_root(ws_root).join(safe_id))
}

pub fn require_task_dir(ws_root: &Path, task_id: &str) -> Result<PathBuf, WbError> {
    let tdir = task_dir_for(ws_root, task_id)?;
    if !tdir.join("task.yaml").is_file() {
        return Err(WbError::not_found(format!("任务不存在: {task_id}")));
    }
    Ok(tdir)
}

pub fn load_task(ws_root: &Path, task_id: &str) -> Result<Value, WbError> {
    let tdir = require_task_dir(ws_root, task_id)?;
    let data = read_yaml_file(&tdir.join("task.yaml"))?;
    validate_task_dict(&data)
}

fn append_progress_locked(
    tdir: &Path,
    task_id: &str,
    message: &str,
    status: &str,
    timestamp: &str,
) -> Result<(), WbError> {
    let progress_path = tdir.join("progress.md");
    let clean_msg = message.trim();
    if clean_msg.is_empty() {
        return Err(WbError::validation("进展内容不能为空"));
    }

    let mut prefix = String::new();
    let meta = fs::metadata(&progress_path).ok();
    if meta.as_ref().map(|m| m.len()).unwrap_or(0) == 0 {
        prefix = format!("# {task_id} 进展记录\n");
    } else {
        let mut rf = OpenOptions::new()
            .read(true)
            .open(&progress_path)
            .map_err(|e| WbError::io(format!("读取进展文件失败 {}: {e}", progress_path.display())))?;
        rf.seek(SeekFrom::End(-1))
            .map_err(|e| WbError::io(format!("定位进展文件末尾失败 {}: {e}", progress_path.display())))?;
        let mut last = [0u8; 1];
        rf.read_exact(&mut last)
            .map_err(|e| WbError::io(format!("读取进展文件末尾失败 {}: {e}", progress_path.display())))?;
        if last[0] != b'\n' {
            prefix.push('\n');
        }
    }

    let entry = format!("{prefix}\n## {timestamp} [{status}]\n\n- {clean_msg}\n");
    let mut af = OpenOptions::new()
        .create(true)
        .append(true)
        .open(&progress_path)
        .map_err(|e| WbError::io(format!("追加进展记录失败 {}: {e}", progress_path.display())))?;
    af.write_all(entry.as_bytes())
        .map_err(|e| WbError::io(format!("写入进展记录失败 {}: {e}", progress_path.display())))?;
    af.sync_all()
        .map_err(|e| WbError::io(format!("刷盘进展记录失败 {}: {e}", progress_path.display())))?;
    Ok(())
}

pub fn rebuild_index(ws_root: &Path) -> Result<PathBuf, WbError> {
    let t_root = tasks_root(ws_root);
    fs::create_dir_all(&t_root)
        .map_err(|e| WbError::io(format!("创建 tasks 目录失败: {e}")))?;

    let mut entries: Vec<PathBuf> = fs::read_dir(&t_root)
        .map_err(|e| WbError::io(format!("读取 tasks 目录失败: {e}")))?
        .filter_map(|e| e.ok().map(|x| x.path()))
        .filter(|p| p.is_dir())
        .collect();
    entries.sort();

    let mut rows: Vec<Value> = Vec::new();
    for child in entries {
        let tfile = child.join("task.yaml");
        if !tfile.is_file() {
            continue;
        }
        match read_yaml_file(&tfile).and_then(|v| validate_task_dict(&v)) {
            Ok(data) => rows.push(data),
            Err(_) => {
                let mut err_row = Map::new();
                err_row.insert(
                    "id".into(),
                    Value::String(
                        child
                            .file_name()
                            .map(|s| s.to_string_lossy().into_owned())
                            .unwrap_or_default(),
                    ),
                );
                err_row.insert("title".into(), Value::String("(损坏的 task.yaml)".into()));
                err_row.insert("status".into(), Value::String("error".into()));
                err_row.insert("priority".into(), Value::String("-".into()));
                err_row.insert("category".into(), Value::String("-".into()));
                err_row.insert("owner".into(), Value::String("-".into()));
                err_row.insert("updated_at".into(), Value::String("-".into()));
                rows.push(Value::Object(err_row));
            }
        }
    }

    let mut lines = vec![
        INDEX_HEADER.to_string(),
        String::new(),
        "# 任务总索引".to_string(),
        String::new(),
        "> 本文件由 `wb` 自动生成，请勿手工编辑。".to_string(),
        String::new(),
        "| ID | 标题 | 状态 | 优先级 | 主类 | 负责人 | 更新时间 |".to_string(),
        "| --- | --- | --- | --- | --- | --- | --- |".to_string(),
    ];

    if rows.is_empty() {
        lines.push("| (暂无任务) | - | - | - | - | - | - |".to_string());
    } else {
        for row in rows {
            let id = row.get("id").and_then(|v| v.as_str()).unwrap_or("");
            let title = row
                .get("title")
                .and_then(|v| v.as_str())
                .unwrap_or("")
                .replace('|', "\\|");
            let status = row.get("status").and_then(|v| v.as_str()).unwrap_or("");
            let priority = row.get("priority").and_then(|v| v.as_str()).unwrap_or("");
            let category = row.get("category").and_then(|v| v.as_str()).unwrap_or("");
            let owner = row.get("owner").and_then(|v| v.as_str()).unwrap_or("");
            let updated_at = row.get("updated_at").and_then(|v| v.as_str()).unwrap_or("");
            lines.push(format!(
                "| {id} | {title} | {status} | {priority} | {category} | {owner} | {updated_at} |"
            ));
        }
    }
    lines.push(String::new());

    let index_path = t_root.join("INDEX.md");
    atomic_write_text(&index_path, &lines.join("\n"))?;
    Ok(index_path)
}

pub fn load_session_ledger(ws_root: &Path) -> Result<Value, WbError> {
    let ledger_path = tasks_root(ws_root).join("session-types.json");
    if !ledger_path.is_file() {
        let mut m = Map::new();
        m.insert("schema".into(), Value::from(SCHEMA_SESSION_TYPES));
        m.insert("sessions".into(), Value::Array(Vec::new()));
        return Ok(Value::Object(m));
    }
    let data = read_json_file(&ledger_path)?;
    let obj = data
        .as_object()
        .ok_or_else(|| WbError::validation(format!("session-types.json 格式无效: {}", ledger_path.display())))?;
    if !obj.get("sessions").map(|v| v.is_array()).unwrap_or(false) {
        return Err(WbError::validation(format!(
            "session-types.json 格式无效: {}",
            ledger_path.display()
        )));
    }
    Ok(data)
}

#[allow(clippy::too_many_arguments)]
fn upsert_session_ledger_locked(
    ws_root: &Path,
    session_id: &str,
    host: &str,
    title: &str,
    prefix: Option<&str>,
    category: &str,
    task_id: Option<&str>,
    recorded_at: &str,
) -> Result<Value, WbError> {
    let mut ledger = load_session_ledger(ws_root)?;
    let sessions = ledger
        .as_object_mut()
        .unwrap()
        .get_mut("sessions")
        .unwrap()
        .as_array_mut()
        .unwrap();

    let mut found_idx: Option<usize> = None;
    for (idx, entry) in sessions.iter().enumerate() {
        if entry.get("session_id").and_then(|v| v.as_str()) == Some(session_id)
            && entry.get("host").and_then(|v| v.as_str()) == Some(host)
        {
            found_idx = Some(idx);
            break;
        }
    }

    let result = match found_idx {
        None => {
            let mut m = Map::new();
            m.insert("session_id".into(), Value::String(session_id.to_string()));
            m.insert("host".into(), Value::String(host.to_string()));
            m.insert("title".into(), Value::String(title.to_string()));
            m.insert(
                "prefix".into(),
                prefix
                    .map(|p| Value::String(p.to_string()))
                    .unwrap_or(Value::Null),
            );
            m.insert("category".into(), Value::String(category.to_string()));
            let tids = match task_id {
                Some(tid) => vec![Value::String(tid.to_string())],
                None => Vec::new(),
            };
            m.insert("task_ids".into(), Value::Array(tids));
            m.insert("updated_at".into(), Value::String(recorded_at.to_string()));
            let v = Value::Object(m);
            sessions.push(v.clone());
            v
        }
        Some(idx) => {
            let target = sessions[idx].as_object_mut().unwrap();
            target.insert("title".into(), Value::String(title.to_string()));
            target.insert(
                "prefix".into(),
                prefix
                    .map(|p| Value::String(p.to_string()))
                    .unwrap_or(Value::Null),
            );
            target.insert("category".into(), Value::String(category.to_string()));
            target.insert("updated_at".into(), Value::String(recorded_at.to_string()));
            let mut task_ids: Vec<String> = target
                .get("task_ids")
                .and_then(|v| v.as_array())
                .map(|arr| {
                    arr.iter()
                        .filter_map(|x| x.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default();
            if let Some(tid) = task_id {
                if !task_ids.iter().any(|x| x == tid) {
                    task_ids.push(tid.to_string());
                }
            }
            target.insert(
                "task_ids".into(),
                Value::Array(task_ids.into_iter().map(Value::String).collect()),
            );
            Value::Object(target.clone())
        }
    };

    atomic_write_json(&tasks_root(ws_root).join("session-types.json"), &ledger)?;
    Ok(result)
}

#[derive(Debug, Default)]
pub struct CreateTaskOpts<'a> {
    pub task_id: &'a str,
    pub title: &'a str,
    pub goal: &'a str,
    pub status: &'a str,
    pub priority: &'a str,
    pub owner: &'a str,
    pub category: &'a str,
    pub components: &'a [String],
    pub origin_session_id: Option<&'a str>,
    pub origin_host: Option<&'a str>,
    pub origin_title: Option<&'a str>,
    pub origin_category: Option<&'a str>,
    pub timestamp: Option<&'a str>,
}

pub fn create_task(ws_root: &Path, opts: CreateTaskOpts<'_>) -> Result<Value, WbError> {
    let safe_id = validate_task_id(opts.task_id)?;
    let clean_title = opts.title.trim();
    if clean_title.is_empty() {
        return Err(WbError::validation("任务标题不能为空"));
    }
    let status = validate_status(if opts.status.is_empty() { "planning" } else { opts.status })?;
    let priority = validate_priority(if opts.priority.is_empty() { "P2" } else { opts.priority })?;
    let category = validate_category(if opts.category.is_empty() {
        "unclassified"
    } else {
        opts.category
    })?;
    let ts = opts.timestamp.map(str::to_string).unwrap_or_else(now_iso);

    let tdir = task_dir_for(ws_root, &safe_id)?;
    if tdir.exists() && tdir.join("task.yaml").exists() {
        return Err(WbError::conflict(format!("任务已存在: {safe_id}")));
    }

    let mut dedup_components: Vec<String> = Vec::new();
    for comp in opts.components {
        let c = comp.trim();
        if !c.is_empty() && !dedup_components.iter().any(|x| x == c) {
            dedup_components.push(c.to_string());
        }
    }

    let mut origin_entry: Option<Map<String, Value>> = None;
    if let Some(sid) = opts.origin_session_id {
        let s_id = sid.trim();
        if !s_id.is_empty() {
            let s_host = opts
                .origin_host
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("localhost");
            let raw_s_title = opts
                .origin_title
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or(clean_title);
            let (norm_title, prefix, inferred_cat) = parse_and_validate_session_title(raw_s_title)?;
            let s_cat = match opts.origin_category {
                Some(c) if !c.is_empty() => validate_category(c)?,
                _ => inferred_cat.unwrap_or_else(|| "unclassified".to_string()),
            };
            let mut m = Map::new();
            m.insert("session_id".into(), Value::String(s_id.to_string()));
            m.insert("host".into(), Value::String(s_host.to_string()));
            m.insert("title".into(), Value::String(norm_title));
            m.insert(
                "prefix".into(),
                prefix.map(Value::String).unwrap_or(Value::Null),
            );
            m.insert("category".into(), Value::String(s_cat));
            m.insert("recorded_at".into(), Value::String(ts.clone()));
            origin_entry = Some(m);
        }
    }

    let mut sessions_obj = Map::new();
    sessions_obj.insert(
        "origin".into(),
        origin_entry
            .clone()
            .map(Value::Object)
            .unwrap_or(Value::Null),
    );
    sessions_obj.insert("associated".into(), Value::Array(Vec::new()));

    let mut task_map = Map::new();
    task_map.insert("schema".into(), Value::from(SCHEMA_TASK));
    task_map.insert("id".into(), Value::String(safe_id.clone()));
    task_map.insert("title".into(), Value::String(clean_title.to_string()));
    task_map.insert("goal".into(), Value::String(opts.goal.trim().to_string()));
    task_map.insert("status".into(), Value::String(status.clone()));
    task_map.insert("priority".into(), Value::String(priority));
    task_map.insert("owner".into(), Value::String(opts.owner.trim().to_string()));
    task_map.insert("category".into(), Value::String(category));
    task_map.insert(
        "components".into(),
        Value::Array(dedup_components.into_iter().map(Value::String).collect()),
    );
    task_map.insert("milestones".into(), Value::Array(Vec::new()));
    task_map.insert("blockers".into(), Value::Array(Vec::new()));
    task_map.insert("next_steps".into(), Value::Array(Vec::new()));
    task_map.insert("docs".into(), Value::Array(Vec::new()));
    task_map.insert("materials".into(), Value::Array(Vec::new()));
    task_map.insert("links".into(), Value::Array(Vec::new()));
    task_map.insert("sessions".into(), Value::Object(sessions_obj));
    task_map.insert("created_at".into(), Value::String(ts.clone()));
    task_map.insert("updated_at".into(), Value::String(ts.clone()));

    let task_data = Value::Object(task_map);

    fs::create_dir_all(tdir.join("delivery-history"))
        .map_err(|e| WbError::io(format!("创建任务目录失败: {e}")))?;
    fs::create_dir_all(tdir.join("evidence"))
        .map_err(|e| WbError::io(format!("创建证据目录失败: {e}")))?;

    with_task_lock(&tdir, |_| {
        if tdir.join("task.yaml").exists() {
            return Err(WbError::conflict(format!("任务已存在: {safe_id}")));
        }
        atomic_write_yaml(&tdir.join("task.yaml"), &task_data)?;
        append_progress_locked(
            &tdir,
            &safe_id,
            &format!("创建任务：{clean_title}"),
            &status,
            &ts,
        )
    })?;

    with_workspace_lock(ws_root, |_| {
        if let Some(ref origin) = origin_entry {
            upsert_session_ledger_locked(
                ws_root,
                origin["session_id"].as_str().unwrap(),
                origin["host"].as_str().unwrap(),
                origin["title"].as_str().unwrap(),
                origin["prefix"].as_str(),
                origin["category"].as_str().unwrap(),
                Some(&safe_id),
                &ts,
            )?;
        }
        rebuild_index(ws_root)?;
        Ok(())
    })?;

    Ok(task_data)
}

pub fn update_task_status(
    ws_root: &Path,
    task_id: &str,
    status: &str,
    note: Option<&str>,
) -> Result<Value, WbError> {
    let status = validate_status(status)?;
    let tdir = require_task_dir(ws_root, task_id)?;
    let ts = now_iso();

    let updated = with_task_lock(&tdir, |_| {
        let mut data = validate_task_dict(&read_yaml_file(&tdir.join("task.yaml"))?)?;
        let obj = data.as_object_mut().unwrap();
        let old_status = obj["status"].as_str().unwrap_or("").to_string();
        obj.insert("status".into(), Value::String(status.clone()));
        obj.insert("updated_at".into(), Value::String(ts.clone()));
        atomic_write_yaml(&tdir.join("task.yaml"), &data)?;

        let suffix = note
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(|s| format!("（{s}）"))
            .unwrap_or_default();
        let msg = format!("状态变更：{old_status} -> {status}{suffix}");
        append_progress_locked(&tdir, task_id, &msg, &status, &ts)?;
        Ok(data)
    })?;

    with_workspace_lock(ws_root, |_| {
        rebuild_index(ws_root)?;
        Ok(())
    })?;
    Ok(updated)
}

pub fn append_progress(ws_root: &Path, task_id: &str, message: &str) -> Result<Value, WbError> {
    let tdir = require_task_dir(ws_root, task_id)?;
    let ts = now_iso();

    let updated = with_task_lock(&tdir, |_| {
        let mut data = validate_task_dict(&read_yaml_file(&tdir.join("task.yaml"))?)?;
        let status = data["status"].as_str().unwrap_or("planning").to_string();
        append_progress_locked(&tdir, task_id, message, &status, &ts)?;
        data.as_object_mut()
            .unwrap()
            .insert("updated_at".into(), Value::String(ts.clone()));
        atomic_write_yaml(&tdir.join("task.yaml"), &data)?;
        Ok(data)
    })?;

    with_workspace_lock(ws_root, |_| {
        rebuild_index(ws_root)?;
        Ok(())
    })?;
    Ok(updated)
}

fn mutate_task_list_field(
    ws_root: &Path,
    task_id: &str,
    field: &str,
    action: &str,
    value: &str,
    index: Option<usize>,
    deduplicate: bool,
) -> Result<Value, WbError> {
    let tdir = require_task_dir(ws_root, task_id)?;
    let ts = now_iso();
    let clean_val = value.trim();

    let updated = with_task_lock(&tdir, |_| {
        let mut data = validate_task_dict(&read_yaml_file(&tdir.join("task.yaml"))?)?;
        let obj = data.as_object_mut().unwrap();
        let mut items: Vec<Value> = obj
            .get(field)
            .and_then(|v| v.as_array())
            .cloned()
            .unwrap_or_default();

        match action {
            "add" => {
                if clean_val.is_empty() {
                    return Err(WbError::validation(format!("{field} 添加值不能为空")));
                }
                let val_node = Value::String(clean_val.to_string());
                if !deduplicate || !items.iter().any(|x| x == &val_node) {
                    items.push(val_node);
                }
            }
            "remove" => {
                if let Some(idx) = index {
                    if idx >= items.len() {
                        return Err(WbError::not_found(format!("{field} 索引超出范围: {idx}")));
                    }
                    items.remove(idx);
                } else {
                    let before = items.len();
                    items.retain(|x| x.as_str() != Some(clean_val));
                    if items.len() == before {
                        return Err(WbError::not_found(format!("{field} 中未找到条目: {clean_val}")));
                    }
                }
            }
            "clear" => {
                items.clear();
            }
            _ => {
                return Err(WbError::validation(format!("不支持的列表操作: {action}")));
            }
        }

        obj.insert(field.to_string(), Value::Array(items));
        obj.insert("updated_at".into(), Value::String(ts.clone()));
        atomic_write_yaml(&tdir.join("task.yaml"), &data)?;
        Ok(data)
    })?;

    with_workspace_lock(ws_root, |_| {
        rebuild_index(ws_root)?;
        Ok(())
    })?;
    Ok(updated)
}

